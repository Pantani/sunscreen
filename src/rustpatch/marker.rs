/// Strip the leading `// ===` (with arbitrary whitespace around the slashes
/// and the equals sequence). Returns the slice after the `===`.
fn strip_marker_prefix(line: &str) -> Option<&str> {
    let line = line.strip_prefix("//")?;
    let line = line.trim_start();
    line.strip_prefix("===")
}

/// Parse a marker tail like
/// `segment=foo version=1 generator=cli ===`
/// into (key, value) pairs. The trailing `===` and any whitespace is
/// tolerated.
fn parse_attrs(s: &str, line: usize) -> Result<Vec<(String, String)>, RustpatchError> {
    // Drop trailing `===` if present.
    let s = s.trim();
    let s = s.strip_suffix("===").unwrap_or(s).trim();

    let mut out = Vec::new();
    for tok in s.split_whitespace() {
        let Some((k, v)) = tok.split_once('=') else {
            return Err(RustpatchError::Malformed {
                line: line + 1,
                detail: format!("attribute `{tok}` is not key=value"),
            });
        };
        out.push((k.to_string(), v.to_string()));
    }
    Ok(out)
}

fn require_attr(
    attrs: &[(String, String)],
    key: &str,
    line: usize,
) -> Result<String, RustpatchError> {
    attrs
        .iter()
        .find(|(k, _)| k == key)
        .map(|(_, v)| v.clone())
        .ok_or_else(|| RustpatchError::Malformed {
            line: line + 1,
            detail: format!("missing required attribute `{key}`"),
        })
}

