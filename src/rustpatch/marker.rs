#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scan_empty_source() {
        let m = scan("").unwrap();
        assert!(m.is_empty());
    }

    #[test]
    fn scan_no_markers() {
        let src = "fn main() {}\n";
        assert!(scan(src).unwrap().is_empty());
    }

    #[test]
    fn scan_single_auto_generated() {
        let src = "\
prefix
    // === sunscreen:auto-generated:begin segment=foo version=2 ===
body1
body2
    // === sunscreen:auto-generated:end segment=foo ===
suffix
";
        let m = scan(src).unwrap();
        assert_eq!(m.len(), 1);
        assert_eq!(m[0].segment, "foo");
        assert_eq!(m[0].version, 2);
        assert_eq!(m[0].kind, MarkerKind::AutoGenerated);
        assert_eq!(m[0].begin, 1);
        assert_eq!(m[0].end, 4);
    }

    #[test]
    fn scan_user_region() {
        let src = "\
// === sunscreen:user-region:begin segment=handler ===
let x = 1;
// === sunscreen:user-region:end segment=handler ===
";
        let m = scan(src).unwrap();
        assert_eq!(m.len(), 1);
        assert_eq!(m[0].kind, MarkerKind::UserRegion);
        assert_eq!(m[0].segment, "handler");
    }

    #[test]
    fn scan_multiple_segments() {
        let src = "\
// === sunscreen:auto-generated:begin segment=a version=1 ===
// === sunscreen:auto-generated:end segment=a ===
// === sunscreen:auto-generated:begin segment=b version=1 ===
// === sunscreen:auto-generated:end segment=b ===
";
        let m = scan(src).unwrap();
        assert_eq!(m.len(), 2);
        assert_eq!(m[0].segment, "a");
        assert_eq!(m[1].segment, "b");
    }

    #[test]
    fn scan_unbalanced_missing_end() {
        let src = "// === sunscreen:auto-generated:begin segment=foo version=1 ===\n";
        let err = scan(src).unwrap_err();
        assert!(matches!(err, RustpatchError::Unbalanced { .. }));
    }

    #[test]
    fn scan_unbalanced_stray_end() {
        let src = "// === sunscreen:auto-generated:end segment=foo ===\n";
        let err = scan(src).unwrap_err();
        assert!(matches!(err, RustpatchError::Unbalanced { .. }));
    }

    #[test]
    fn scan_rejects_crossing_pairs() {
        // begin a; begin b; end a; end b — crossing (non-LIFO) nesting must
        // be rejected as unbalanced.
        let src = "\
// === sunscreen:auto-generated:begin segment=a version=1 ===
// === sunscreen:auto-generated:begin segment=b version=1 ===
// === sunscreen:auto-generated:end segment=a ===
// === sunscreen:auto-generated:end segment=b ===
";
        let err = scan(src).unwrap_err();
        assert!(matches!(err, RustpatchError::Unbalanced { .. }));
    }

    #[test]
    fn scan_duplicate_segment() {
        let src = "\
// === sunscreen:auto-generated:begin segment=foo version=1 ===
// === sunscreen:auto-generated:begin segment=foo version=1 ===
// === sunscreen:auto-generated:end segment=foo ===
// === sunscreen:auto-generated:end segment=foo ===
";
        let err = scan(src).unwrap_err();
        assert!(matches!(err, RustpatchError::Duplicate { .. }));
    }

    #[test]
    fn scan_sequential_duplicate_segment() {
        let src = "\
// === sunscreen:auto-generated:begin segment=foo version=1 ===
// body
// === sunscreen:auto-generated:end segment=foo ===
// === sunscreen:auto-generated:begin segment=foo version=1 ===
// body2
// === sunscreen:auto-generated:end segment=foo ===
";
        let err = scan(src).unwrap_err();
        assert!(matches!(err, RustpatchError::Duplicate { .. }));
    }

    #[test]
    fn scan_malformed_missing_segment() {
        let src = "// === sunscreen:auto-generated:begin version=1 ===\n";
        let err = scan(src).unwrap_err();
        assert!(matches!(err, RustpatchError::Malformed { .. }));
    }

    #[test]
    fn apply_replaces_body() {
        let src = "\
header
// === sunscreen:auto-generated:begin segment=foo version=1 ===
old1
old2
// === sunscreen:auto-generated:end segment=foo ===
footer
";
        let patches = vec![Patch {
            segment: "foo".to_string(),
            lines: vec!["new1".to_string(), "new2".to_string(), "new3".to_string()],
        }];
        let out = apply(src, &patches).unwrap();
        let expected = "\
header
// === sunscreen:auto-generated:begin segment=foo version=1 ===
new1
new2
new3
// === sunscreen:auto-generated:end segment=foo ===
footer
";
        assert_eq!(out, expected);
    }

    #[test]
    fn apply_is_idempotent() {
        let src = "\
// === sunscreen:auto-generated:begin segment=foo version=1 ===
old
// === sunscreen:auto-generated:end segment=foo ===
";
        let patches = vec![Patch {
            segment: "foo".to_string(),
            lines: vec!["L1".to_string(), "L2".to_string()],
        }];
        let once = apply(src, &patches).unwrap();
        let twice = apply(&once, &patches).unwrap();
        assert_eq!(once, twice);
    }

    #[test]
    fn apply_preserves_outside_content() {
        let src = "\
a
b
// === sunscreen:auto-generated:begin segment=foo version=1 ===
x
// === sunscreen:auto-generated:end segment=foo ===
c
d
";
        let patches = vec![Patch {
            segment: "foo".to_string(),
            lines: vec!["y".to_string()],
        }];
        let out = apply(src, &patches).unwrap();
        assert!(out.starts_with("a\nb\n"));
        assert!(out.ends_with("c\nd\n"));
        assert!(out.contains("\ny\n"));
        assert!(!out.contains("\nx\n"));
    }

    #[test]
    fn apply_unknown_segment_errors() {
        let src = "\
// === sunscreen:auto-generated:begin segment=foo version=1 ===
// === sunscreen:auto-generated:end segment=foo ===
";
        let patches = vec![Patch {
            segment: "bar".to_string(),
            lines: vec![],
        }];
        let err = apply(src, &patches).unwrap_err();
        assert!(matches!(err, RustpatchError::UnknownSegment(_)));
    }

    #[test]
    fn apply_user_region_forbidden() {
        let src = "\
// === sunscreen:user-region:begin segment=handler ===
// === sunscreen:user-region:end segment=handler ===
";
        let patches = vec![Patch {
            segment: "handler".to_string(),
            lines: vec![],
        }];
        let err = apply(src, &patches).unwrap_err();
        assert!(matches!(err, RustpatchError::UserRegionPatch(_)));
    }

    #[test]
    fn apply_multiple_patches_in_order() {
        let src = "\
// === sunscreen:auto-generated:begin segment=a version=1 ===
oldA
// === sunscreen:auto-generated:end segment=a ===
middle
// === sunscreen:auto-generated:begin segment=b version=1 ===
oldB
// === sunscreen:auto-generated:end segment=b ===
";
        let patches = vec![
            Patch {
                segment: "b".into(),
                lines: vec!["newB".into()],
            },
            Patch {
                segment: "a".into(),
                lines: vec!["newA".into()],
            },
        ];
        let out = apply(src, &patches).unwrap();
        assert!(out.contains("newA"));
        assert!(out.contains("newB"));
        assert!(!out.contains("oldA"));
        assert!(!out.contains("oldB"));
    }

    #[test]
    fn apply_empty_body() {
        let src = "\
// === sunscreen:auto-generated:begin segment=foo version=1 ===
oldline
// === sunscreen:auto-generated:end segment=foo ===
";
        let patches = vec![Patch {
            segment: "foo".into(),
            lines: vec![],
        }];
        let out = apply(src, &patches).unwrap();
        let expected = "\
// === sunscreen:auto-generated:begin segment=foo version=1 ===
// === sunscreen:auto-generated:end segment=foo ===
";
        assert_eq!(out, expected);
    }
}
