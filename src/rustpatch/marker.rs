//! Marker scan + apply.
//!
//! Line-oriented string scan. No regex.

use thiserror::Error;

/// Kind of marker pair.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MarkerKind {
    /// CLI-owned region. Body is rewritten by [`apply`].
    AutoGenerated,
    /// User-owned region. Body is preserved.
    UserRegion,
}

/// Resolved marker pair.
///
/// `begin` and `end` are zero-based **line indices** (not byte offsets).
/// `begin` points at the begin-marker line; `end` points at the end-marker
/// line. The replaceable body lives in `(begin, end)` (exclusive both ends).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Marker {
    pub segment: String,
    pub version: u32,
    pub begin: usize,
    pub end: usize,
    pub kind: MarkerKind,
}

/// A single patch targeting an auto-generated segment.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Patch {
    pub segment: String,
    /// Replacement body lines. Each entry becomes one line in the output
    /// (no trailing newline characters; `apply` re-joins with `\n`).
    pub lines: Vec<String>,
}

/// Errors produced by [`scan`] / [`apply`].
#[derive(Debug, Error, PartialEq, Eq)]
pub enum RustpatchError {
    #[error("malformed marker on line {line}: {detail}")]
    Malformed { line: usize, detail: String },
    #[error("unbalanced marker for segment `{segment}` (line {line})")]
    Unbalanced { segment: String, line: usize },
    #[error("duplicate marker for segment `{segment}` (line {line})")]
    Duplicate { segment: String, line: usize },
    #[error("patch targets unknown segment `{0}`")]
    UnknownSegment(String),
    #[error("patch targets a user-region segment `{0}` (forbidden)")]
    UserRegionPatch(String),
}

/// Scan `source` for marker pairs, returning them in source order.
pub fn scan(source: &str) -> Result<Vec<Marker>, RustpatchError> {
    // First pass: collect every marker line as a partial record.
    enum Half {
        AgBegin { segment: String, version: u32 },
        AgEnd { segment: String },
        UrBegin { segment: String },
        UrEnd { segment: String },
    }

    let mut halves: Vec<(usize, Half)> = Vec::new();
    for (idx, raw) in source.lines().enumerate() {
        let line = raw.trim_start();
        // All markers start with `// ===`.
        let Some(rest) = strip_marker_prefix(line) else {
            continue;
        };
        let rest = rest.trim();

        if let Some(after) = rest.strip_prefix("sunscreen:auto-generated:begin") {
            let attrs = parse_attrs(after, idx)?;
            let segment = require_attr(&attrs, "segment", idx)?;
            let version_raw = require_attr(&attrs, "version", idx)?;
            let version: u32 = version_raw.parse().map_err(|_| RustpatchError::Malformed {
                line: idx + 1,
                detail: format!("version `{version_raw}` is not a u32"),
            })?;
            halves.push((idx, Half::AgBegin { segment, version }));
        } else if let Some(after) = rest.strip_prefix("sunscreen:auto-generated:end") {
            let attrs = parse_attrs(after, idx)?;
            let segment = require_attr(&attrs, "segment", idx)?;
            halves.push((idx, Half::AgEnd { segment }));
        } else if let Some(after) = rest.strip_prefix("sunscreen:user-region:begin") {
            let attrs = parse_attrs(after, idx)?;
            let segment = require_attr(&attrs, "segment", idx)?;
            halves.push((idx, Half::UrBegin { segment }));
        } else if let Some(after) = rest.strip_prefix("sunscreen:user-region:end") {
            let attrs = parse_attrs(after, idx)?;
            let segment = require_attr(&attrs, "segment", idx)?;
            halves.push((idx, Half::UrEnd { segment }));
        }
        // Otherwise: a `// ===` comment that isn't a sunscreen marker. Ignore.
    }

    // Second pass: pair them up. We require strict LIFO matching per kind:
    // every begin must be closed by the next end of the same kind+segment
    // before any other begin of the same segment opens.
    let mut markers: Vec<Marker> = Vec::new();
    // Stack tracks open begins so we can detect unbalanced pairs cleanly.
    let mut stack: Vec<(usize, MarkerKind, String, u32)> = Vec::new();

    for (line, half) in halves {
        match half {
            Half::AgBegin { segment, version } => {
                if stack
                    .iter()
                    .any(|(_, k, s, _)| *k == MarkerKind::AutoGenerated && s == &segment)
                {
                    return Err(RustpatchError::Duplicate {
                        segment,
                        line: line + 1,
                    });
                }
                stack.push((line, MarkerKind::AutoGenerated, segment, version));
            }
            Half::UrBegin { segment } => {
                if stack
                    .iter()
                    .any(|(_, k, s, _)| *k == MarkerKind::UserRegion && s == &segment)
                {
                    return Err(RustpatchError::Duplicate {
                        segment,
                        line: line + 1,
                    });
                }
                stack.push((line, MarkerKind::UserRegion, segment, 0));
            }
            Half::AgEnd { segment } => {
                // Strict LIFO: an end must close the MOST RECENT open begin,
                // and that begin must match this end's kind+segment. Crossing
                // pairs (begin a; begin b; end a; end b) are rejected.
                let Some((begin, kind, seg, ver)) = stack.pop() else {
                    return Err(RustpatchError::Unbalanced {
                        segment,
                        line: line + 1,
                    });
                };
                if kind != MarkerKind::AutoGenerated || seg != segment {
                    return Err(RustpatchError::Unbalanced {
                        segment,
                        line: line + 1,
                    });
                }
                markers.push(Marker {
                    segment: seg,
                    version: ver,
                    begin,
                    end: line,
                    kind,
                });
            }
            Half::UrEnd { segment } => {
                // Strict LIFO (see AgEnd above).
                let Some((begin, kind, seg, _)) = stack.pop() else {
                    return Err(RustpatchError::Unbalanced {
                        segment,
                        line: line + 1,
                    });
                };
                if kind != MarkerKind::UserRegion || seg != segment {
                    return Err(RustpatchError::Unbalanced {
                        segment,
                        line: line + 1,
                    });
                }
                markers.push(Marker {
                    segment: seg,
                    version: 0,
                    begin,
                    end: line,
                    kind,
                });
            }
        }
    }

    if let Some((line, _kind, segment, _)) = stack.into_iter().next() {
        return Err(RustpatchError::Unbalanced {
            segment,
            line: line + 1,
        });
    }

    markers.sort_by_key(|m| m.begin);

    // Post-pass: reject sequential duplicates (same kind+segment appears more
    // than once in the resolved list).
    {
        use std::collections::HashSet;
        let mut seen: HashSet<(u8, String)> = HashSet::new();
        for m in &markers {
            let kind_key: u8 = match m.kind {
                MarkerKind::AutoGenerated => 0,
                MarkerKind::UserRegion => 1,
            };
            if !seen.insert((kind_key, m.segment.clone())) {
                return Err(RustpatchError::Duplicate {
                    segment: m.segment.clone(),
                    line: m.begin + 1,
                });
            }
        }
    }

    Ok(markers)
}

/// Apply `patches` to `source`, returning the rewritten source.
///
/// Each patch's `segment` must match an `AutoGenerated` marker present in
/// `source`. User-region segments are read-only; patching one returns
/// [`RustpatchError::UserRegionPatch`]. Unknown segments return
/// [`RustpatchError::UnknownSegment`].
///
/// Idempotency: `apply(apply(s, p), p) == apply(s, p)`.
pub fn apply(source: &str, patches: &[Patch]) -> Result<String, RustpatchError> {
    let markers = scan(source)?;

    // Resolve every patch up-front.
    let mut planned: Vec<(usize, usize, &[String])> = Vec::with_capacity(patches.len());
    for patch in patches {
        let m = markers
            .iter()
            .find(|m| m.segment == patch.segment)
            .ok_or_else(|| RustpatchError::UnknownSegment(patch.segment.clone()))?;
        if m.kind == MarkerKind::UserRegion {
            return Err(RustpatchError::UserRegionPatch(patch.segment.clone()));
        }
        planned.push((m.begin, m.end, patch.lines.as_slice()));
    }
    planned.sort_by_key(|(b, _, _)| *b);

    // Detect overlapping ranges (should never happen — scan is non-overlap
    // for same-segment, but a defensive check is cheap).
    for w in planned.windows(2) {
        if w[0].1 >= w[1].0 {
            return Err(RustpatchError::Malformed {
                line: w[1].0 + 1,
                detail: "overlapping patch ranges".to_string(),
            });
        }
    }

    let lines: Vec<&str> = source.lines().collect();
    let mut out: Vec<String> = Vec::with_capacity(lines.len() + 16);
    let mut cursor = 0usize;
    for (begin, end, body) in planned {
        // Copy through the begin-marker line itself.
        while cursor <= begin {
            out.push(lines[cursor].to_string());
            cursor += 1;
        }
        // Skip old body.
        cursor = end;
        // Inject new body verbatim.
        for line in body {
            out.push(line.clone());
        }
        // The end-marker line will be copied on next iteration / tail.
    }
    while cursor < lines.len() {
        out.push(lines[cursor].to_string());
        cursor += 1;
    }

    let mut result = out.join("\n");
    // Preserve a trailing newline if the input had one.
    if source.ends_with('\n') {
        result.push('\n');
    }
    Ok(result)
}

