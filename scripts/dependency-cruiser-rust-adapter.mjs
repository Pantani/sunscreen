import fs from "node:fs";
import path from "node:path";

const sourceRoot = path.resolve("src");
const outputRoot = path.resolve(".dependency-cruiser-rust");
const moduleOutputRoot = path.join(outputRoot, "modules", "src");
const layerOutputRoot = path.join(outputRoot, "layers", "src");

const IDENT = "[A-Za-z_][A-Za-z0-9_]*";
const CRATE_PATH_RE = new RegExp(`\\bcrate::\\s*(${IDENT}(?:::\\s*${IDENT})*)`, "g");
const USE_TREE_RE = /use\s+crate::\s*\{([\s\S]*?)\};/g;

function walkRustFiles(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      files.push(...walkRustFiles(fullPath));
      continue;
    }

    if (entry.isFile() && entry.name.endsWith(".rs")) {
      files.push(fullPath);
    }
  }

  return files;
}

function toPosix(value) {
  return value.split(path.sep).join("/");
}

function moduleIdForRustFile(filePath) {
  const relative = toPosix(path.relative(sourceRoot, filePath));

  if (relative === "main.rs") {
    return "main";
  }

  if (relative === "lib.rs") {
    return "lib";
  }

  const withoutExtension = relative.replace(/\.rs$/, "");

  if (withoutExtension.endsWith("/mod")) {
    return withoutExtension.slice(0, -"/mod".length);
  }

  return withoutExtension;
}

function jsPathForModuleId(moduleId) {
  return `${moduleId}.js`;
}

function splitTopLevel(value) {
  const items = [];
  let depth = 0;
  let start = 0;

  for (let index = 0; index < value.length; index += 1) {
    const char = value[index];

    if (char === "{") {
      depth += 1;
    } else if (char === "}") {
      depth -= 1;
    } else if (char === "," && depth === 0) {
      items.push(value.slice(start, index));
      start = index + 1;
    }
  }

  items.push(value.slice(start));
  return items;
}

function stripAlias(value) {
  return value.replace(/\s+as\s+.*$/s, "").trim();
}

function parseUseTree(value, prefix = []) {
  const paths = [];

  for (const rawItem of splitTopLevel(value)) {
    const item = rawItem.trim();

    if (!item) {
      continue;
    }

    const braceIndex = item.indexOf("{");

    if (braceIndex >= 0) {
      const beforeBrace = item.slice(0, braceIndex).replace(/::\s*$/, "").trim();
      const afterBrace = item.slice(braceIndex + 1, item.lastIndexOf("}"));
      const baseSegments = stripAlias(beforeBrace)
        .split("::")
        .map((segment) => segment.trim())
        .filter(Boolean);
      const nextPrefix = [...prefix, ...baseSegments];

      if (nextPrefix.length > 0) {
        paths.push(nextPrefix);
      }

      paths.push(...parseUseTree(afterBrace, nextPrefix));
      continue;
    }

    const segments = stripAlias(item)
      .split("::")
      .map((segment) => segment.trim())
      .filter(Boolean);

    if (segments.length === 0 || segments[0] === "self" || segments[0] === "super") {
      continue;
    }

    paths.push([...prefix, ...segments]);
  }

  return paths;
}

function resolveModuleId(segments, knownModules) {
  for (let length = segments.length; length > 0; length -= 1) {
    const candidate = segments.slice(0, length).join("/");

    if (knownModules.has(candidate)) {
      return candidate;
    }
  }

  return null;
}

function relativeImport(fromFile, toFile) {
  let relative = toPosix(path.relative(path.dirname(fromFile), toFile));

  if (!relative.startsWith(".")) {
    relative = `./${relative}`;
  }

  return relative;
}

function collectDependencies(filePath, moduleId, knownModules) {
  const source = fs.readFileSync(filePath, "utf8");
  const dependencies = new Set();
  const cratePaths = [];
  let match;

  while ((match = CRATE_PATH_RE.exec(source)) !== null) {
    cratePaths.push(match[1].replace(/\s+/g, "").split("::"));
  }

  while ((match = USE_TREE_RE.exec(source)) !== null) {
    cratePaths.push(...parseUseTree(match[1]));
  }

  for (const segments of cratePaths) {
    const dependency = resolveModuleId(segments, knownModules);

    if (dependency && dependency !== moduleId) {
      dependencies.add(dependency);
    }
  }

  return dependencies;
}

function writeShadowModule(moduleId, sourceFile, dependencies, modulePathById) {
  const outputFile = path.join(moduleOutputRoot, jsPathForModuleId(moduleId));
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });

  const imports = [...dependencies]
    .sort()
    .map((dependency) => `import "${relativeImport(outputFile, modulePathById.get(dependency))}";`);

  const relativeSource = toPosix(path.relative(process.cwd(), sourceFile));
  const content = [
    `// Generated by scripts/dependency-cruiser-rust-adapter.mjs from ${relativeSource}.`,
    "// Do not edit. This file mirrors Rust module dependencies for Dependency Cruiser.",
    ...imports,
    "",
  ].join("\n");

  fs.writeFileSync(outputFile, content);
}

function writeLayerModule(layerId, dependencies) {
  const outputFile = path.join(layerOutputRoot, `${layerId}.js`);
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });

  const imports = [...dependencies]
    .sort()
    .map((dependency) => `import "./${dependency}.js";`);

  const content = [
    `// Generated top-level Rust dependency layer for ${layerId}.`,
    "// Do not edit. This file mirrors Rust layer dependencies for Dependency Cruiser.",
    ...imports,
    "",
  ].join("\n");

  fs.writeFileSync(outputFile, content);
}

const rustFiles = walkRustFiles(sourceRoot);
const moduleFileById = new Map();

for (const filePath of rustFiles) {
  moduleFileById.set(moduleIdForRustFile(filePath), filePath);
}

const knownModules = new Set(moduleFileById.keys());
const modulePathById = new Map();

fs.rmSync(outputRoot, { recursive: true, force: true });

for (const moduleId of knownModules) {
  modulePathById.set(moduleId, path.join(moduleOutputRoot, jsPathForModuleId(moduleId)));
}

const dependencyByModule = new Map();
const dependencyByLayer = new Map();

for (const [moduleId, filePath] of moduleFileById) {
  const dependencies = collectDependencies(filePath, moduleId, knownModules);
  dependencyByModule.set(moduleId, dependencies);

  const fromLayer = moduleId.split("/")[0];

  if (!dependencyByLayer.has(fromLayer)) {
    dependencyByLayer.set(fromLayer, new Set());
  }

  for (const dependency of dependencies) {
    const toLayer = dependency.split("/")[0];

    if (toLayer !== fromLayer) {
      dependencyByLayer.get(fromLayer).add(toLayer);
    }
  }
}

for (const [moduleId, filePath] of moduleFileById) {
  writeShadowModule(moduleId, filePath, dependencyByModule.get(moduleId), modulePathById);
}

for (const layerId of new Set([...knownModules].map((moduleId) => moduleId.split("/")[0]))) {
  writeLayerModule(layerId, dependencyByLayer.get(layerId) ?? new Set());
}

console.log(
  `Generated ${moduleFileById.size} Rust dependency shadow modules and ${dependencyByLayer.size} top-level layer modules.`,
);
